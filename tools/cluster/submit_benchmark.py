#!/usr/bin/env python3
"""Write the Slurm array scripts for the benchmark sweep. Submits nothing, ever.

This is P34's ``submit.py`` for the one sweep that exists. It takes a benchmark
set, writes one ``sbatch`` array script per leg, and **prints the exact
``sbatch`` command for you to run yourself**. It does not call ``sbatch``, it
has no ``--submit`` flag, and it should not grow one: a cluster allocation is a
shared, accounted resource, and the policy beside this checkout is explicit that
nothing in this repository submits, cancels or polls on its own.

    python3 tools/cluster/submit_benchmark.py --set fast
    python3 tools/cluster/submit_benchmark.py --set complete --max-parallel 6

**Three arrays, not one**, because ``--partition`` and ``--gpus`` are properties
of a job and these three legs want different ones:

* ``qe``  -- ``pw.x`` from the cluster's own module, one core;
* ``cpu`` -- defumat in the virtualenv, one core, both batching dials at QE's end;
* ``gpu`` -- defumat on one GPU, both dials at the batched end.

They are joined afterwards by case name: every task writes
``<work>/results/<set>/<case>.<leg>.json``, and ``performance/sweep.py --report``
reads the directory whichever subset of the three has landed. That is also why a
failed or queued leg costs only its own column.

**One array task is one case**, which is what the site policy asks for -- short
tasks grouped into one array rather than submitted individually -- and it means
a task that dies takes one cell's number with it rather than the sweep's.

**The ``#SBATCH`` values are inherited, not invented.** Partitions, the GPU
specification and the CPU counts are the ones in the committed, already-run
``tools/gpu/sweep-qe.sbatch`` and ``sweep-gpu.sbatch``; the time limits are
those scripts' whole-loop budgets divided down to one case. Every one of them is
a flag here, and anything you change should be checked against
<https://scicomp.aalto.fi/triton/> rather than against this file.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from performance import sets  # noqa: E402

#: Inherited from tools/gpu/sweep-qe.sbatch and sweep-gpu.sbatch, which have run
#: on this cluster. Time is per *case* here, where those were per whole loop.
DEFAULTS = {
    "qe": {"partition": "batch-csl", "cpus": 1, "mem": "64G",
           "time": {"fast": "01:00:00", "complete": "04:00:00"}},
    "cpu": {"partition": "batch-csl", "cpus": 1, "mem": "64G",
            "time": {"fast": "01:00:00", "complete": "04:00:00"}},
    "gpu": {"partition": "gpu-h200-141g-short", "gpus": "h200:1", "cpus": 4, "mem": "160G",
            "time": {"fast": "01:00:00", "complete": "02:00:00"}},
}

HEADER = """#!/bin/bash
# {title}
#
# Generated by tools/cluster/submit_benchmark.py -- edit the generator, not this
# file, or the next regeneration will discard the change.
#
# One array task is one case. Every task writes one JSON record; nothing here
# writes per-iteration output, because the site's small-files policy is about
# exactly that.
#SBATCH --job-name={job_name}
#SBATCH --partition={partition}
#SBATCH --time={time}
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task={cpus}
#SBATCH --mem={mem}
{gpu_line}#SBATCH --array=0-{last}%{max_parallel}
#SBATCH --output={work}/out/{leg}-%A_%a.out
#SBATCH --error={work}/out/{leg}-%A_%a.err

set -u
WORK={work}
REPO={repo}
SET={set_name}
RESULTS="$WORK/results/$SET"
mkdir -p "$WORK/out" "$RESULTS" || exit 1
cd "$REPO" || exit 1

# A batch shell does not source .bashrc, so the environment is set out in full.
export OMP_NUM_THREADS=1 MKL_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1
export PYTHONPATH="$REPO"

CASES=(
{cases}
)
CASE="${{CASES[$SLURM_ARRAY_TASK_ID]}}"

echo "=== $CASE / {leg} ==="; hostname; date
"""

FOOT = """
echo; echo "=== done ==="; date
"""

QE_BODY = """
# pw.x comes from the module; the version is whatever the cluster carries (7.2
# at the time of writing, against the 7.5 vendored in this repo), and it lands
# in the record beside the number rather than being assumed.
module load {qe_module} || exit 1
export PW_X="$(command -v pw.x)"
[ -x "$PW_X" ] || {{ echo "no pw.x after module load"; exit 1; }}

# The virtualenv goes on last so its python wins: the measurement harness is
# this repository's, even though the binary it times is the module's.
source "{venv}/bin/activate" || exit 1
echo "pw.x: $PW_X"; python3 -c "import sys; print('python', sys.version.split()[0])"

srun python3 performance/sweep.py --measure "$CASE" --leg qe \\
     --json "$RESULTS/$CASE.qe.json" --repeats {repeats} \\
     --max-iterations {max_iterations}
echo "exit $?"
"""

DEFUMAT_BODY = """
source "{venv}/bin/activate" || exit 1
python3 -c "import jax; print('jax', jax.__version__, jax.devices())"
git -C "$REPO" rev-parse HEAD
{gpu_probe}
# The kernel cache is OFF for a benchmark, deliberately, and this is the one
# place that choice costs something. A shared cache on scratch would save every
# task minutes of recompilation -- and would also mean a "cold" run is reading a
# concurrent task's compilation, which is precisely the number this measures.
srun python3 performance/sweep.py --measure "$CASE" --leg {leg} \\
     --json "$RESULTS/$CASE.{leg}.json" --repeats {repeats} \\
     --k-batch {k_batch} --band-batch {band_batch} \\
     --cache off --max-iterations {max_iterations}
echo "exit $?"
"""


def write_script(leg: str, case_names: list[str], arguments) -> Path:
    """One leg's array script. Returns where it was written."""
    spec = DEFAULTS[leg]
    titles = {
        "qe": "Quantum ESPRESSO on one core -- the baseline the CPU claim is against.",
        "cpu": "defumat on one core -- the project's own metric, beside the QE array.",
        "gpu": "defumat on one GPU -- against the CPU array, per SCF iteration (GPU.md 2.3).",
    }
    text = HEADER.format(
        title=titles[leg],
        job_name=f"defumat-bench-{leg}-{arguments.set}",
        partition=arguments.partition.get(leg) or spec["partition"],
        time=arguments.time.get(leg) or spec["time"][arguments.set],
        cpus=spec["cpus"],
        mem=arguments.mem.get(leg) or spec["mem"],
        gpu_line=f"#SBATCH --gpus={spec['gpus']}\n" if leg == "gpu" else "",
        last=len(case_names) - 1,
        max_parallel=arguments.max_parallel,
        work=arguments.work,
        repo=arguments.repo,
        leg=leg,
        set_name=arguments.set,
        cases="\n".join(f"  {name}" for name in case_names),
    )
    if leg == "qe":
        text += QE_BODY.format(qe_module=arguments.qe_module, venv=arguments.venv,
                               repeats=arguments.repeats,
                               max_iterations=arguments.max_iterations)
    else:
        text += DEFUMAT_BODY.format(
            venv=arguments.venv, leg=leg, repeats=arguments.repeats,
            max_iterations=arguments.max_iterations,
            k_batch="all" if leg == "gpu" else "1",
            band_batch="all" if leg == "gpu" else "1",
            gpu_probe=('nvidia-smi --query-gpu=name,driver_version,memory.total '
                       '--format=csv,noheader\n' if leg == "gpu" else ""))
    text += FOOT

    path = arguments.out_dir / f"bench-{leg}-{arguments.set}.sbatch"
    path.write_text(text)
    path.chmod(0o755)
    return path


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--set", default="fast", choices=sorted(sets.SETS))
    parser.add_argument("--legs", nargs="+", default=list(DEFAULTS), choices=list(DEFAULTS),
                        metavar="LEG", help="which arrays to write (default: all three)")
    parser.add_argument("--out-dir", type=Path,
                        default=ROOT / "performance" / "cluster" / "generated",
                        help="where the .sbatch files are written")
    parser.add_argument("--work", default="/scratch/work/ladovj1/calculations/defumat-bench",
                        help="the run directory on scratch: results, logs, nothing else")
    parser.add_argument("--repo", default="/scratch/work/ladovj1/apps/defumat",
                        help="the checkout on the cluster")
    parser.add_argument("--venv", default=None,
                        help="the virtualenv (default: <work>/venv)")
    parser.add_argument("--qe-module", default="quantum-espresso/7.2",
                        help="the module that provides pw.x; check `module spider` first")
    parser.add_argument("--max-parallel", type=int, default=4,
                        help="the array's %%N throttle -- concurrent tasks, not total")
    parser.add_argument("--repeats", type=int, default=2,
                        help="SCF runs per task: the first compiles, the rest are warm")
    parser.add_argument("--max-iterations", type=int, default=100)
    parser.add_argument("--partition", action=_KeyValue, default={}, metavar="LEG=NAME")
    parser.add_argument("--time", action=_KeyValue, default={}, metavar="LEG=HH:MM:SS")
    parser.add_argument("--mem", action=_KeyValue, default={}, metavar="LEG=SIZE")
    arguments = parser.parse_args(argv)
    arguments.venv = arguments.venv or f"{arguments.work}/venv"
    arguments.out_dir.mkdir(parents=True, exist_ok=True)

    case_names = [case.name for case in sets.cases(arguments.set)]
    written = [(leg, write_script(leg, case_names, arguments)) for leg in arguments.legs]

    print(f"set {arguments.set}: {len(case_names)} cases, "
          f"{len(written)} arrays of {len(case_names)} tasks each\n")
    for leg, path in written:
        print(f"  {leg:3s}  {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}")

    print(f"""
Nothing has been submitted. To run the sweep, copy the scripts to the cluster if
they were generated here, and submit them yourself:

    rsync -av {arguments.out_dir}/ ladovj1@code.triton.aalto.fi:{arguments.work}/sbatch/
""")
    for leg, path in written:
        print(f"    sbatch {arguments.work}/sbatch/{path.name}")
    print(f"""
Then bring the records back and typeset them locally -- the cluster runs defumat
and pw.x, and nothing else:

    rsync -av ladovj1@code.triton.aalto.fi:{arguments.work}/results/{arguments.set}/ \\
        performance/results/{arguments.set}/
    python3 performance/sweep.py --report performance/results/{arguments.set} --set {arguments.set}

Check before the first submission, because these are inherited rather than
looked up: the partition, the time limit and the {arguments.qe_module} module all
have to still exist. `module spider quantum-espresso` and
<https://scicomp.aalto.fi/triton/> are the authorities, not this script.""")
    return 0


class _KeyValue(argparse.Action):
    """``--time gpu=02:00:00 cpu=00:30:00`` -- a per-leg override."""

    def __call__(self, parser, namespace, values, option_string=None):
        mapping = dict(getattr(namespace, self.dest) or {})
        for item in ([values] if isinstance(values, str) else values):
            key, _, value = item.partition("=")
            if key not in DEFAULTS or not value:
                parser.error(f"{option_string} wants LEG=VALUE with LEG in {list(DEFAULTS)}")
            mapping[key] = value
        setattr(namespace, self.dest, mapping)


if __name__ == "__main__":
    raise SystemExit(main())
